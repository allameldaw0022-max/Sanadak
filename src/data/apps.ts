export function getAppBySlug(slug: string): AppItem | undefined {
  return apps.find((a) => a.slug === slug);
}

export function getFeaturedApps(): AppItem[] {
  return apps.filter((a) => a.featured);
}

export function getLatestApps(limit = 8): AppItem[] {
  return [...apps]
    .sort((a, b) => new Date(b.lastUpdate).getTime() - new Date(a.lastUpdate).getTime())
    .slice(0, limit);
}

export function getMostDownloadedApps(limit = 8): AppItem[] {
  return [...apps].sort((a, b) => b.downloads - a.downloads).slice(0, limit);
}

export function getAppsByCategory(categorySlug: string): AppItem[] {
  return apps.filter((a) => a.categorySlug === categorySlug);
}

export function getSimilarApps(app: AppItem, limit = 4): AppItem[] {
  return apps
    .filter((a) => a.categorySlug === app.categorySlug && a.id !== app.id)
    .slice(0, limit);
}

export function searchApps(query: string): AppItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return apps.filter(
    (a) =>
      a.name.toLowerCase().includes(q) ||
      a.developer.toLowerCase().includes(q) ||
      a.shortDescription.toLowerCase().includes(q)
  );
}
